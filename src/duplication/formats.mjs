export const supportedFormats = Object.freeze(
  Object.keys(formatExtensions).sort(),
);
const byExtension = new Map(
  Object.entries(formatExtensions).flatMap(([format, exts]) =>
    exts.map((ext) => [ext, format]),
  ),
);
const byName = new Map(
  Object.entries(formatNames).flatMap(([format, names]) =>
    names.map((name) => [name, format]),
  ),
);
/** Mirrors pinned native extension/shebang priority; named routes and MDX are explicit additions. */
export function formatForPath(path, source = "") {
  const named = byName.get(basename(path));
  const extension = byExtension.get(extname(path).slice(1));
  if (named || extension) return named ?? extension;
  const first = source.split(/\r?\n/u, 1)[0];
  if (!first.startsWith("#!")) return null;
  if (first.includes("python")) return "python";
  if (first.includes("node")) return "javascript";
  if (first.includes("ruby")) return "ruby";
  if (first.includes("bash") || first.includes("/sh")) return "bash";
  if (first.includes("perl")) return "perl";
  if (first.includes("php")) return "php";
  return null;
}
